let current = "en";

export function uiLang(locale) {
  const code = String(locale || "en")
    .trim()
    .slice(0, 2)
    .toLowerCase();
  if (code === "tr") return "tr";
  if (code === "nb" || code === "nn" || code === "no") return "nb";
  return "en";
}

export function setLang(locale) {
  current = uiLang(locale);
  return current;
}

export function lang() {
  return current;
}

export function t(key) {
  const table = TABLES[current] || TABLES.en;
  return table[key] ?? TABLES.en[key] ?? key;
}

export function petName(id) {
  return t(id);
}
